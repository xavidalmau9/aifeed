#!/usr/bin/env python3
"""Syncs the Nov 16 2026 story-selection and caption changes into the n8n fallback (automation/n8n/AIFeed_Autopilot.json).

- Fetch RSS + Dedup: the rank prompt from automation/actions/lib/rss.js (topic priorities, stat-only demotion).
- Pick Slot Story: the topic nudge from automation/actions/lib/topics.js applied to the model's ranking.
- Fetch Articles: the igQuestion field in the caption prompt (automation/actions/lib/articles.js).
- Quality Checks + Build HTML, Layout Check, Merge LI Caption: the closing question instead of the newsletter CTA
  (automation/actions/lib/captions.js); captions with the old CTA still pass checkIg.
Idempotent: run it again after editing those files. test/n8n-fallback.test.js checks the result.
"""
import json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WF = os.path.join(ROOT, 'n8n', 'AIFeed_Autopilot.json')
A = os.path.join(ROOT, 'actions', 'lib')
d = json.load(open(WF))
N = {n['name']: n for n in d['nodes']}

def code(name): return N[name]['parameters']['jsCode']
def setcode(name, c): N[name]['parameters']['jsCode'] = c

# 1. Rank prompt: copy the template literal of buildRankPrompt from rss.js.
rss = open(os.path.join(A, 'rss.js')).read()
new_prompt = re.search(r'return `(You are the editor of AIFeed\.run[\s\S]*?)`;\n}', rss).group(1)
c = code('Fetch RSS + Dedup')
m = re.search(r'`(You are the editor of AIFeed\.run[\s\S]*?)`', c)
assert m, 'rank prompt not found in Fetch RSS + Dedup'
c = c[:m.start(1)] + new_prompt + c[m.end(1):]
setcode('Fetch RSS + Dedup', c)

# 2. Topic nudge in Pick Slot Story.
TB, TE = '// TOPIC MIX LIB\n', '// END TOPIC MIX LIB\n'
topics = open(os.path.join(A, 'topics.js')).read()
topics = topics[:topics.index('module.exports')].rstrip() + '\n'
c = code('Pick Slot Story')
if TB in c: c = c[:c.index(TB)] + c[c.index(TE) + len(TE):]
c = TB + '// generated by automation/n8n/sync_topics_captions.py from automation/actions/lib/topics.js\n' + topics + TE + c
old_parse = "try { ranked = JSON.parse((txt.match(/\\[[\\s\\S]*\\]/) || ['[]'])[0]); } catch (e) { ranked = []; }\n"
nudge = "ranked = applyTopicMix(Array.isArray(ranked) ? ranked : [], base.fresh); // topic mix (lib/topics.js)\n"
assert old_parse in c, 'Pick Slot Story rank parse not recognised'
if nudge not in c: c = c.replace(old_parse, old_parse + nudge)
old_fb = "if (!ordered.length) ordered = base.fresh.slice(0, 12); // Claude failed -> recency order"
new_fb = "if (!ordered.length) ordered = applyTopicMix(base.fresh.slice(0, 12).map((f, i) => ({ index: i + 1 })), base.fresh).map(r => base.fresh[r.index - 1]); // Claude failed -> recency order + topic mix"
if old_fb in c: c = c.replace(old_fb, new_fb)
assert new_fb in c
setcode('Pick Slot Story', c)

# 3. igQuestion in the caption prompt.
art = open(os.path.join(A, 'articles.js')).read()
qline = re.search(r'(- igQuestion: [^\n]*\n)', art).group(1)
c = code('Fetch Articles')
if '- igQuestion:' not in c:
    assert '- igHashtags: exactly 5' in c
    c = c.replace('- igHashtags: exactly 5', qline + '- igHashtags: exactly 5', 1)
c = c.replace('"igParagraphs":["..."],"liHook"', '"igParagraphs":["..."],"igQuestion":"...?","liHook"')
setcode('Fetch Articles', c)

# 4. Closing question in the three caption-builder copies.
cap = open(os.path.join(A, 'captions.js')).read()
helpers = cap[cap.index('// Closing question (Nov 2026)'):cap.index('function buildIg(g, url) {')]
helpers = "const IG_CTA = '📩 Free weekly AI brief at aifeed.run → link in bio';\n" + helpers
QB, QE = '// CLOSING QUESTION LIB\n', '// END CLOSING QUESTION LIB\n'
for name in ['Quality Checks + Build HTML', 'Layout Check', 'Merge LI Caption']:
    c = code(name)
    if QB in c: c = c[:c.index(QB)] + c[c.index(QE) + len(QE):]
    assert 'function buildIg(g, url) {' in c, name
    c = c.replace('function buildIg(g, url) {', QB + helpers + QE + 'function buildIg(g, url) {', 1)
    c = c.replace("`Source: ${normText(g.outlet)} · ${cleanUrl(url)}`, '📩 Free weekly AI brief at aifeed.run → link in bio', tg.map",
                  "`Source: ${normText(g.outlet)} · ${cleanUrl(url)}`, Q_PREFIX + closingQuestion(g), tg.map")
    c = c.replace("if ((blocks[n - 2] || '') !== '📩 Free weekly AI brief at aifeed.run → link in bio') e.push('brief CTA line malformed (must sit alone after a spacer below Source)');",
                  "if (!isCloser(blocks[n - 2] || '')) e.push('closing question line malformed (one short question, alone after a spacer below Source)');")
    c = c.replace('// hook + 3-4 paras + source + brief CTA + hashtags', '// hook + 3-4 paras + source + closing question (or the legacy brief CTA) + hashtags')
    c = c.replace('(want hook + 3-4 paragraphs + source + brief CTA + hashtags)', '(want hook + 3-4 paragraphs + source + closing question + hashtags)')
    assert 'Q_PREFIX + closingQuestion(g)' in c and 'isCloser(blocks[n - 2]' in c, name
    setcode(name, c)

open(WF, 'w').write(json.dumps(d, indent=2, ensure_ascii=True) + '\n')
print('synced')
